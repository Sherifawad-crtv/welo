// Extracts the Solar icons we use from @iconify-json/solar into src/solarIcons.js
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const set = require('@iconify-json/solar/icons.json');

const names = [
  'user-linear', 'info-circle-linear', 'alt-arrow-left-linear', 'alt-arrow-right-linear', 'alt-arrow-down-linear',
  'home-2-bold', 'home-2-linear', 'chart-2-bold', 'chart-2-linear', 'add-linear', 'arrow-left-linear', 'close-linear',
  'pen-linear', 'trash-bin-trash-linear', 'notes-linear', 'scale-linear', 'target-linear', 'ruler-linear',
  'calendar-linear', 'user-circle-linear', 'camera-linear', 'bell-linear', 'lock-linear', 'document-text-linear',
  'shield-check-linear', 'heart-linear', 'letter-linear', 'moon-linear', 'plate-linear',
  'dumbbell-large-minimalistic-linear', 'cup-hot-linear', 'waterdrop-linear', 'microphone-linear', 'minus-linear', 'check-read-linear', 'undo-left-linear',
  ...['scale', 'target', 'ruler', 'calendar', 'user-circle', 'camera', 'bell', 'lock', 'document-text', 'shield-check', 'heart', 'letter'].map((n) => `${n}-bold-duotone`),
];
const out = {};
for (const n of names) {
  if (!set.icons[n]) throw new Error(`Missing Solar icon: ${n}`);
  out[n] = set.icons[n].body;
}
writeFileSync(new URL('../src/solarIcons.js', import.meta.url),
  `// GENERATED by scripts/gen-icons.mjs (Solar icon set, CC BY 4.0). Do not edit.\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${names.length} icons`);
